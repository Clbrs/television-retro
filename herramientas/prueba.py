import asyncio, json, urllib.request
from playwright.async_api import async_playwright
U = 'http://127.0.0.1:8765/?local&script=/script#clave=' + 'a' * 64
def est(q=''): return json.loads(urllib.request.urlopen('http://127.0.0.1:8765/_estado' + q).read())
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(channel='chrome', args=['--autoplay-policy=no-user-gesture-required'])
        ctx = await b.new_context(viewport={'width': 1280, 'height': 800}, bypass_csp=True); pg = await ctx.new_page()
        pg.on('console', lambda m: print('CONSOLE', m.type, m.text))
        pg.on('pageerror', lambda e: print('PAGEERROR', e))
        await pg.goto(U); await pg.wait_for_selector('.canal-boton')
        await pg.screenshot(path='/tmp/s1_menu.png')
        await pg.click('.canal-boton')
        await pg.wait_for_function('document.querySelector("#video").currentTime > 2', timeout=30000)
        await pg.wait_for_timeout(3000)
        print('t', await pg.evaluate('video.currentTime'), 'paused', await pg.evaluate('video.paused'))
        await pg.screenshot(path='/tmp/s2_canal.png')
        await pg.click('#play'); await pg.wait_for_timeout(1000)
        print('tras pausa paused', await pg.evaluate('video.paused'), 'clase', await pg.evaluate('document.querySelector("#canal").className'))
        await pg.screenshot(path='/tmp/s3_pausa.png')
        print('estado', est()['estado'])
        await pg.click('#casa'); await pg.wait_for_timeout(500)
        est('?n=1&t=1512')
        await pg.click('.canal-boton')
        await pg.wait_for_function('video.currentTime > 1512', timeout=30000)
        print('reanuda en', await pg.evaluate('video.currentTime'))
        await pg.wait_for_function('document.querySelector("#siguiente").classList.contains("visible")', timeout=30000)
        await pg.wait_for_timeout(1500); await pg.screenshot(path='/tmp/s4_siguiente.png')
        await pg.wait_for_function('!video.paused && video.currentTime > 1 && video.currentTime < 60', timeout=40000)
        print('cap siguiente t', await pg.evaluate('video.currentTime'), est()['estado'])
        # reiniciar con pulsación larga
        await pg.wait_for_timeout(4000)
        box = await pg.query_selector('#reiniciar'); bb = await box.bounding_box()
        await pg.mouse.move(bb['x'] + 30, bb['y'] + 30); await pg.mouse.down(); await pg.wait_for_timeout(500); await pg.mouse.up()
        await pg.wait_for_timeout(800); print('toque corto, t', await pg.evaluate('video.currentTime'))
        await pg.mouse.down(); await pg.wait_for_timeout(1900); await pg.mouse.up()
        await pg.wait_for_function('!video.paused && video.currentTime > 0.2', timeout=30000)
        print('tras reiniciar t', await pg.evaluate('video.currentTime'))
        await pg.set_viewport_size({'width': 400, 'height': 860}); await pg.wait_for_timeout(800)
        await pg.screenshot(path='/tmp/s5_vertical.png')
        print('log', [x[1:4] for x in est()['log']][-8:])
        await b.close()
asyncio.run(main())
